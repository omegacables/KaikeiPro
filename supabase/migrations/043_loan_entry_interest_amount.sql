-- ============================================================================
-- 043_loan_entry_interest_amount
-- 返済明細に「同時に支払った利息」を持たせる。
--
-- 銀行返済は元金と利息を同時に現金で払う。このとき利息は費用であって、
-- 借入金の残高を増やすものではない。
--   借方 借入金   100,000
--   借方 支払利息   2,400
--   貸方 普通預金 102,400
--
-- 042 までは利息を entry_type='interest' の別明細として作っていたため、
--   借方 支払利息 2,400 / 貸方 借入金 2,400
-- となり、残高が利息分だけ増えてしまっていた。
--
-- entry_type='interest' は「未払利息を元本に加算する」計上を表すもので、
-- 支払済みの利息とは別物なので、区分を分けずに専用の列を持たせる。
-- ============================================================================

ALTER TABLE loan_entries
    ADD COLUMN IF NOT EXISTS interest_amount integer NOT NULL DEFAULT 0
        CHECK (interest_amount >= 0);

COMMENT ON COLUMN loan_entries.interest_amount IS
    'entry_type=''repay'' のときに同時に支払った利息。費用として仕訳に載るが、残高は動かさない。';

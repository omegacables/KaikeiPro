-- ============================================================================
-- 041_statutory_interest_rate_by_loan_year
-- 認定利息の利率マスタを「会計年度」軸から「貸付けを行った暦年」軸へ修正する。
--
-- 040 では fiscal_year（会計年度）をキーにしていたが、これは誤りだった。
-- 役員・使用人への貸付に適用する利率は
--   「貸付けを行った日の属する年」の利子税特例基準割合による利率
-- で決まり（所得税基本通達36-49 / 国税庁タックスアンサー No.2606）、
-- その後に年が変わっても、その貸付に対する利率は変わらない。
-- 会計年度でも「当年」でもなく、貸付実行時の暦年で固定される。
--
-- 例: 2022年に貸し付けた残高は、2026年時点でも 0.9% のまま
--     （2026年の 1.3% は 2026年に行った貸付にのみ適用される）
--
-- そのため残高を1つに合算すると利率を決められない。アプリ側は貸付実行ごとの
-- トランシェで利率を保持し、返済はFIFOで充当する（src/lib/loan-ledger.ts）。
-- ============================================================================

ALTER TABLE statutory_interest_rates
    RENAME COLUMN fiscal_year TO loan_year;

COMMENT ON COLUMN statutory_interest_rates.loan_year IS
    '貸付けを行った日の属する年（暦年）。会計年度ではない。';
COMMENT ON TABLE statutory_interest_rates IS
    '役員等への貸付に適用する認定利息の利率。国税庁タックスアンサー No.2606 の公表値。';


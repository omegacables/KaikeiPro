-- ============================================================================
-- 046_loan_counterparty_aliases
-- 相手先の別名（通帳での表記）を持たせる。
--
-- 通帳に載る名前と台帳の名前は一致しない（「アンドウ レン」と「検証用社長」）。
-- 名前の一致に頼ると突き合わせは必ず失敗し、毎回人が選び直すことになる。
--
-- 学習（暗黙）ではなく明示的な登録にするのは、会計システムでは
-- 「どう紐付いているかが見えること」「間違いを直せること」が要るため。
-- 税務調査で仕訳の根拠を説明できる必要もある。
-- 登録の手間は、人が選んだ直後に「登録しますか」と提案することで実質ゼロにする。
-- ============================================================================

ALTER TABLE loans
    ADD COLUMN IF NOT EXISTS aliases text[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN loans.aliases IS
    '通帳・振込明細での表記ゆれ。読み取った相手先名をこの台帳に結び付けるために使う。';

CREATE INDEX IF NOT EXISTS idx_loans_aliases ON loans USING gin (aliases);

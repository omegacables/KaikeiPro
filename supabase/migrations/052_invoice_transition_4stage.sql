-- 免税事業者等からの仕入れに係る経過措置を4段階に対応させる。
--
-- 平成28年改正法附則52・53の経過措置は、当初「80%（3年）→50%（3年）→終了」
-- だったが、**令和8年度改正で期限が2年延長され4段階**になった。
--
--   〜令和8年9月30日                  80%
--   令和8年10月1日〜令和10年9月30日    70%   ← 新設
--   令和10年10月1日〜令和12年9月30日   50%
--   令和12年10月1日〜令和13年9月30日   30%   ← 新設
--   令和13年10月1日以後                なし
--
-- 税区分マスタには 80% と 50% しか無く、このままでは令和8年10月1日以降の
-- 課税仕入れに正しい税区分を割り当てられない。
-- 既存の 80%・50% はそのまま残す（過年度の仕訳が参照しているため）。
insert into tax_categories (code, name, rate, is_purchase, transition_rate)
values
  ('purchase_10_trans_70', '課税仕入10%（経過措置70%）', 0.10, true, 0.70),
  ('purchase_08_trans_70', '課税仕入8%（経過措置70%）',  0.08, true, 0.70),
  ('purchase_10_trans_30', '課税仕入10%（経過措置30%）', 0.10, true, 0.30),
  ('purchase_08_trans_30', '課税仕入8%（経過措置30%）',  0.08, true, 0.30)
on conflict (code) do nothing;

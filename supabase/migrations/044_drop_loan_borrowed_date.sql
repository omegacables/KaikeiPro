-- ============================================================================
-- 044_drop_loan_borrowed_date
-- loans.borrowed_date を廃止する。
--
-- 旧設計（1レコード＝1本の借入）で「当初借入額」と対にして持っていた列だが、
-- 040 で増減明細方式に変えた時点で役目を終えていた。借入の実行日は
-- loan_entries の「借入」の行が持つため、ヘッダー側に持つ意味がない。
--
-- 使われないまま入力欄だけが残っていると「何を入れる欄なのか」と迷わせる。
-- 040 で principal を非推奨にした際に、この列を消し忘れていた。
-- ============================================================================

-- すでにコードは参照していないため、ここで落として構わない。
-- 念のため、明細に日付が無い台帳が残っていないか確認できるようにコメントを残す。
COMMENT ON COLUMN loans.borrowed_date IS
    '廃止予定（044）。借入日は loan_entries の entry_date を使う。';

ALTER TABLE loans DROP COLUMN IF EXISTS borrowed_date;

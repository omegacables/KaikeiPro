-- 令和8年（2026年）の認定利息の利率を、国税庁の公表値で確定させる。
--
-- 041 で登録した時点ではタックスアンサー No.2606 が令和7年分までしか
-- 更新されておらず、「平均貸付割合0.8% ＋ 0.5% ＝ 1.3%」と自分で計算した
-- 推定値を入れていた。
-- その後ページが「令和8年4月1日現在法令等」に更新され、
-- 「令和8年中に貸し付けたもの … 1.3パーセント」と明記されたため、
-- 値は変えず、根拠だけを推定から公表値に改める。
--
-- 併せて平成22年〜令和7年の全17年分を公表値と突き合わせ、すべて一致を確認した。
-- 令和9年以降は未公表。未登録の年は試算を出さず「利率が未登録」と表示する
-- 作りになっているため（imputedInterestAlert の missingRateYears）、
-- 推測値を先回りして入れることはしない。
update statutory_interest_rates
   set note = '令和8年。国税庁タックスアンサー No.2606（令和8年4月1日現在法令等）で確認'
 where loan_year = 2026;

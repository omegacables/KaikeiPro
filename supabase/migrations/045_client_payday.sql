-- ============================================================================
-- 045_client_payday
-- 顧問先ごとの給料日を保持する。
--
-- 給与を登録するとき、支給日の初期値をコードに「25日」と直接書いていた。
-- 給料日は会社ごとに違い（末日・10日・25日など）、月次で必ず使う値なので、
-- 毎回打ち直すのは手間になる。顧問先の設定として持たせる。
--
-- 「末日」は月によって28〜31日と変わるため、日にちの数値では表せない。
-- 0 を末日の意味に使う（1〜31 はその日にち）。
-- ============================================================================

ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS payday int
        CHECK (payday IS NULL OR (payday >= 0 AND payday <= 31));

COMMENT ON COLUMN clients.payday IS
    '給料日。1〜31 はその日にち、0 は末日、NULL は未設定。給与登録時の支給日の初期値に使う。';
